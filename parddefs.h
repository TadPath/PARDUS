// FW ROBOVOX T2/T3 (14.10.2026): the duty of a PWM M-Level table row.
// The duty is carried from the server to the Arduino in the second 32-bit word
// of the INFO_ML_LEVEL value (it always was; parduino_fixed3 narrowed it to 8
// bits only at the call to analogEmit()).  From this version:
//
//   duty 0 .. 1000          plain PWM, in PER MILLE (was per cent 0 .. 100):
//                           0 = pin held LOW (silence), 1000 = pin held HIGH.
//   duty 1001 .. 4999       a SPECIAL-EFFECT CODE  duty = 1000 * E + P,
//                           E = effect number (the thousands digit),
//                           P = its parameter (the last three digits).
//                           The row's frequency field is used as stated below.
//
//   E = 1  NOISE        1001..1999  random pulses at the row's frequency (the
//                                   noise clock; capped at FX_MAX_RATE), pulse
//                                   width P per mille of the clock period; a pulse
//                                   is present in a period with probability 1/2
//                                   (16-bit LFSR).  Runs until the next order for
//                                   an actuator on the same timer.
//   E = 2  TIMED NOISE  2001..2999  the same noise for a time, then silence, timed
//                                   on the Arduino (first period always a pulse).
//                                   FW ROBOVOX F7 (parduino_fixed7, 21.10.2026):
//                                   P = 100 c + d.  d = P mod 100 is the time in
//                                   ms (d = 0 means 100 ms); c = P div 100 is the
//                                   WIDTH CLASS: the pulse width is 500 per mille
//                                   shifted right c times (c = 0: 500, 1: 250,
//                                   2: 125, 3: 62, 4: 31, 5: 15, 6: 7, 7: 3,
//                                   8: 1 per mille; each class 6 dB quieter than
//                                   the one before, as long as the width is more
//                                   than one tick: at the 16 kHz clock (TOP 124,
//                                   0.5 us ticks) classes 6, 7 and 8 all give the
//                                   one-tick pulse), and c = 9 is 999 per mille,
//                                   a random TELEGRAPH (the pin HIGH or LOW for
//                                   whole periods, apart from a one-tick LOW notch
//                                   in each HIGH period, since the width is
//                                   clamped to TOP: no strong lines at the clock
//                                   and its harmonics).  Codes 2001..2099 keep
//                                   their meaning (500 per mille, 1..99 ms; for
//                                   c = 0, d = 0 would be the code 2000, which is
//                                   refused, so 500 per mille lasts at most 99
//                                   ms), with two F7 differences: 2030..2099 now
//                                   start with the attack when an attack step is
//                                   set, and a clock of 7 813 Hz or more runs on
//                                   prescaler 8 (16 000 Hz exactly, where
//                                   prescaler 32 gave 16 129 Hz).  Codes
//                                   2100..2999 were 100..999 ms of noise at 500
//                                   per mille in fixed4..fixed6.
//                                   A timed noise of FX_ATTACK_MIN_MS or more on
//                                   Timer 2 starts with the attack (E = 4 below),
//                                   a shorter one (a burst) starts sharply.
//   E = 3  BURST+HISS   3001..3999  a FX_BURST_MS noise burst at width 500 per
//                                   mille, then continuous noise at width P per
//                                   mille (aspiration) until the next order.
//   E = 4  GLIDE        4000..4999  sets the glide (portamento) time of this
//                                   actuator to P milliseconds (4000 = off).  It
//                                   does not change the sound; every following
//                                   PLAIN level of this actuator then walks its
//                                   period (TOP) and pulse width (OCR) linearly,
//                                   one step per period, from the present ones
//                                   to the new ones over P ms.  The row's
//                                   frequency is ignored.
//                                   FW ROBOVOX F5/F7: (a) on a 16-bit timer, a
//                                   plain level that starts a pin that is on its
//                                   timer but SILENT (OCR = 0, a clean silence)
//                                   never walks: the new period and width are set
//                                   at once and the counter is set one tick below
//                                   the new TOP, so the first pulse is whole and
//                                   comes 1.5 periods later (F7; the F5 fade-in,
//                                   a walk from 1 per mille, did not help on
//                                   18.10.2026 -- its 80 ms form was heard as
//                                   '[t]ah' -- and is removed);
//                                   (b) on Timer 2, which has no glides, P is the
//                                   ATTACK STEP of the noises E = 1 (and, F7, of
//                                   E = 2 of FX_ATTACK_MIN_MS or more): with h the
//                                   target width in ticks, the pulse starts at
//                                   ceil(h/8) ticks and grows by ceil(h/8) every
//                                   P ms (at most 255 noise periods: 15.9 ms at
//                                   the 16 000 Hz clock of prescaler 8), the last step
//                                   landing on h: at most eight widths, an
//                                   attack of at most 7 P ms (fewer steps for
//                                   some h, e.g. h = 9: 4 steps; h - 1 steps of
//                                   one tick when h <= 8);
//                                   4000 = a sharp onset (FW_ROBOVOX_NOISE_ATTACK).
//                                   E = 3 and the short E = 2 keep their sharp
//                                   onset (the bursts of the plosives).
//   FW ROBOVOX F7: every noise E = 1, 2, 3 on Timer 2 starts CLEANLY: its first
//                                   pulse is the first pulse of the noise (in
//                                   fixed5/fixed6 a 50 per mille ... 500 per mille
//                                   pulse train, or a stale output state, could
//                                   sound for about a period first: the 'click'
//                                   heard on 18 and 20.10.2026), and a noise whose
//                                   clock is FX_PSC8_MIN_HZ or more runs on the
//                                   Timer-2 prescaler 8 whatever the actuator's
//                                   own prescaler (pulse widths in steps of 0.5 us
//                                   instead of 2 us at prescaler 32: the same
//                                   widths in per mille, a finer realisation).
//   duty 0 (FW ROBOVOX F5, FW_ROBOVOX_CLEAN_SILENCE): on a 16-bit pin that is
//                                   on its timer, OCR = 0 and the pin stays
//                                   hooked (OCR is buffered until BOTTOM: at
//                                   most the first half of one more pulse, then
//                                   a constant LOW); otherwise the pin is
//                                   unhooked and held LOW, as before.
//
// A duty of 1001..4999 with P = 0 (except 4000), or above 4999, is refused by
// the Arduino with PARDU_ERR_INFINVAL.  The server should refuse such a table
// row when it is written (INFO_ML_TTABLE), as it refuses a bad pin.
